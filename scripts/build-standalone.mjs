import { readFile, writeFile } from 'node:fs/promises'
import { basename, resolve } from 'node:path'

const projectRoot = resolve(import.meta.dirname, '..')
const distDir = resolve(projectRoot, 'dist')
const template = await readFile(resolve(distDir, 'index.html'), 'utf8')

const scriptMatch = template.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/)
const styleMatch = template.match(/<link[^>]+href="([^"]+\.css)"[^>]*>/)

if (!scriptMatch || !styleMatch) {
  throw new Error('Could not locate the Vite JavaScript and CSS bundles.')
}

const [javascript, css] = await Promise.all([
  readFile(resolve(distDir, 'assets', basename(scriptMatch[1])), 'utf8'),
  readFile(resolve(distDir, 'assets', basename(styleMatch[1])), 'utf8'),
])

const standalone = template
  .replace(styleMatch[0], `<style>${css.replaceAll('</style', '<\\/style')}</style>`)
  .replace(scriptMatch[0], `<script type="module">${javascript.replaceAll('</script', '<\\/script')}</script>`)
  .replace('<head>', '<head>\n    <!-- Generated by npm run build:html; standalone offline preview. -->')

await writeFile(resolve(projectRoot, 'demo.html'), standalone)
console.log(`Created demo.html (${Buffer.byteLength(standalone).toLocaleString()} bytes)`)
